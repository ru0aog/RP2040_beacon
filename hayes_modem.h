/**  
 * ============================================================================  
 *  hayes_modem.h — Публичный интерфейс эмулятора Hayes-модема (AT-команды)  
 * ============================================================================  
 *  
 *  Эмулятор поднимает ВТОРОЙ виртуальный COM-порт (USB CDC #2, строка  
 *  дескриптора "Beacon Hayes Modem") и ведёт себя как классический  
 *  Hayes-совместимый модем: командный режим AT, набор номера, режим данных,  
 *  выход по escape-последовательности "+++" с guard-time. Консоль маяка (CLI)  
 *  остаётся на первом COM-порту и не затрагивается.  
 *  
 *  "Набор номера" выбирает режим эфира (ATD<режим>[,<частота Гц>]):  
 *    0 — локальная петля (эхо), 1 — CW, 2 — RTTY, 3 — IFKP, 4 — OLIVIA, 5 — THOR.  
 *  В режиме данных каждая строка (до символа S3 = CR) передаётся в эфир  
 *  выбранным модулятором.  
 *  
 *  API:  
 *    hayes_modem_init()         — регистрация второго CDC в TinyUSB; вызывать  
 *                                 в setup() до Serial.begin() (до энумерации).  
 *    hayes_modem_poll()         — неблокирующий опрос порта; вызывать из loop().  
 *    hayes_modem_print_status() — вывод состояния модема в консоль (Serial).  
 *    hayes_modem_is_online()    — true, если "соединение" установлено.  
 * ============================================================================  
 */

#ifndef HAYES_MODEM_H
#define HAYES_MODEM_H

#include <Arduino.h>

void hayes_modem_init();
void hayes_modem_poll();
void hayes_modem_print_status();
bool hayes_modem_is_online();

#endif
