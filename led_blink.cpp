/** @brief Янтарный / Теплый оранжевый цвет. 
 *  Идеален для индикации готовности системы, фиксации частоты VFO в режиме ожидания. */
void ZERO_LED_AMBER_ON() {
    set_rgb_parallel(200, 50, 0); // Плотный красный + немного зеленого дают глубокий янтарь
}

/** @brief Приятный бирюзовый / Морская волна (Cyan). 
 *  Рекомендуется использовать для индикации **активного режима работы SDR-приемника (RX)**. */
void ZERO_LED_CYAN_ON() {
    set_rgb_parallel(0, 120, 140); // Сбалансированное смешение зеленого и синего
}

/** @brief Мягкий пурпурный / Маджента. 
 *  Отлично подойдет для индикации режима **BOOST (активного ВЧ-разгона шины)**. */
void ZERO_LED_MAGENTA_ON() {
    set_rgb_parallel(140, 0, 120);
}

/** @brief Мягкий лимонно-желтый цвет. 
 *  Подходит для индикации работы Guard-систем, например, фазы **Thermal Throttling** (перегрев). */
void ZERO_LED_YELLOW_ON() {
    set_rgb_parallel(140, 110, 0); // Без избыточной ядовитой яркости зеленого
}

/** @brief Лунно-белый цвет сниженной интенсивности. 
 *  Используется как нейтральный индикатор питания, не утомляющий зрение оператора в темноте. */
void ZERO_LED_WHITE_LOW() {
    set_rgb_parallel(45, 50, 45); // Равномерное деление токов по каналам, всего ~18% яркости
}

/** @brief Глубокий индиго / Фиолетовый. 
 *  Приятный глазу цвет. Можно задействовать при включении **узкополосного режима Olivia (`vfo_set_narrowband(true)`)**. */
void ZERO_LED_PURPLE_DEEP() {
    set_rgb_parallel(60, 0, 150);
}

/** @brief Благородный изумрудно-зеленый. 
 *  Более мягкий и премиальный оттенок, чем базовый зеленый. Хорош для статуса "Синхронизация PLL завершена". */
void ZERO_LED_EMERALD_ON() {
    set_rgb_parallel(0, 140, 40);
}

